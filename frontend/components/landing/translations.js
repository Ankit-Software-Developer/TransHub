const DICTIONARIES = { en, hi, mr, gu, es, de };

function deepMerge(base, override) {
  const out = { ...base };
  Object.keys(override || {}).forEach((key) => {
    const value = override[key];
    out[key] =
      value && typeof value === 'object' && !Array.isArray(value)
        ? deepMerge(base[key] || {}, value)
        : value;
  });
  return out;
}

const cache = {};

/** Copy for one language, with English filling any missing key. */
export function getDictionary(code) {
  if (!DICTIONARIES[code] || code === 'en') return en;
  if (!cache[code]) cache[code] = deepMerge(en, DICTIONARIES[code]);
  return cache[code];
}

export function isSupportedLanguage(code) {
  return Boolean(DICTIONARIES[code]);
}
